export function DynamicIcon({ icon, ...props }: { icon: string | null | undefined } & Omit<LucideProps, "name">) {
  if (!icon) return null;
  const Cmp = ICONS[icon] ?? File;
  return <Cmp aria-hidden="true" {...props} />;
}
