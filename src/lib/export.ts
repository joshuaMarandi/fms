"use client";

import { brandLines, SYSTEM_NAME, type CompanyBrand } from "@/lib/branding";

export type ExportColumn = { key: string; header: string };
export type ExportRow = Record<string, unknown>;

/** Who and what a document is for: printed in its header and footer. */
export type DocContext = {
  brand: CompanyBrand | null;
  printedBy: string;
  /** Optional second line under the title, for example the date range or filters. */
  subtitle?: string;
};

function cellText(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (Array.isArray(v)) return v.join(", ");
  if (typeof v === "object") return JSON.stringify(v);
  return String(v);
}

function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

const stamp = () =>
  new Intl.DateTimeFormat("en-GB", { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }).format(new Date());

const safeName = (s: string) => s.replace(/[^\w\- ]+/g, "").trim().replace(/\s+/g, "-").toLowerCase() || "export";

// ---------------------------------------------------------------------------------------------
// CSV: plain data for other systems (no letterhead).
// ---------------------------------------------------------------------------------------------
export function exportCsv(columns: ExportColumn[], rows: ExportRow[], filename: string) {
  const esc = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
  const lines = [columns.map((c) => esc(c.header)).join(",")];
  for (const r of rows) lines.push(columns.map((c) => esc(cellText(r[c.key]))).join(","));
  download(new Blob(["﻿" + lines.join("\n")], { type: "text/csv;charset=utf-8" }), `${safeName(filename)}.csv`);
}

// ---------------------------------------------------------------------------------------------
// Excel: title block (company, details, title, printed by), then the table.
// ---------------------------------------------------------------------------------------------
export async function exportExcel(columns: ExportColumn[], rows: ExportRow[], filename: string, title?: string, ctx?: DocContext) {
  const XLSX = await import("xlsx");
  const head: (string | number)[][] = [];
  if (ctx?.brand) {
    head.push([ctx.brand.name]);
    for (const line of brandLines(ctx.brand)) head.push([line]);
  }
  head.push([title ?? filename]);
  if (ctx?.subtitle) head.push([ctx.subtitle]);
  head.push([`${ctx ? `Printed by ${ctx.printedBy} on ` : "Generated on "}${stamp()}  |  Generated by ${SYSTEM_NAME}  |  ${rows.length} records`]);
  head.push([]);

  const body = rows.map((r) => columns.map((c) => (typeof r[c.key] === "number" ? (r[c.key] as number) : cellText(r[c.key]))));
  const ws = XLSX.utils.aoa_to_sheet([...head, columns.map((c) => c.header), ...body]);
  ws["!cols"] = columns.map((c, i) => ({ wch: Math.min(48, Math.max(12, c.header.length + 2, ...body.slice(0, 200).map((r) => String(r[i] ?? "").length + 2))) }));
  const headerRow = head.length;
  ws["!autofilter"] = { ref: XLSX.utils.encode_range({ s: { r: headerRow, c: 0 }, e: { r: headerRow + body.length, c: Math.max(0, columns.length - 1) } }) };
  ws["!merges"] = head.slice(0, -1).map((_, r) => ({ s: { r, c: 0 }, e: { r, c: Math.max(0, columns.length - 1) } }));
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, (title ?? filename).replace(/[\\/?*[\]:]/g, " ").slice(0, 31));
  XLSX.writeFile(wb, `${safeName(filename)}.xlsx`);
}

// ---------------------------------------------------------------------------------------------
// PDF: letterhead with logo and company details, branded table, quiet footer on every page.
// ---------------------------------------------------------------------------------------------
const BRAND = { primary: [15, 92, 77] as [number, number, number], dark: [15, 61, 52] as [number, number, number], text: [23, 33, 30] as [number, number, number], muted: [85, 98, 94] as [number, number, number], soft: [244, 243, 238] as [number, number, number], line: [221, 220, 212] as [number, number, number] };

const logoCache = new Map<string, Promise<{ data: string; w: number; h: number } | null>>();

/** Fetch the company logo once per session as a PNG data URL with its size. */
function loadLogo(url: string | null | undefined) {
  if (!url) return Promise.resolve(null);
  if (!logoCache.has(url)) {
    logoCache.set(
      url,
      (async () => {
        try {
          const res = await fetch(url, { credentials: "same-origin" });
          if (!res.ok) return null;
          const blob = await res.blob();
          const objectUrl = URL.createObjectURL(blob);
          try {
            const img = await new Promise<HTMLImageElement>((resolve, reject) => {
              const i = new Image();
              i.onload = () => resolve(i);
              i.onerror = reject;
              i.src = objectUrl;
            });
            const canvas = document.createElement("canvas");
            canvas.width = img.naturalWidth || 200;
            canvas.height = img.naturalHeight || 200;
            canvas.getContext("2d")!.drawImage(img, 0, 0, canvas.width, canvas.height);
            return { data: canvas.toDataURL("image/png"), w: canvas.width, h: canvas.height };
          } finally {
            URL.revokeObjectURL(objectUrl);
          }
        } catch {
          return null;
        }
      })(),
    );
  }
  return logoCache.get(url)!;
}

export async function exportPdf(columns: ExportColumn[], rows: ExportRow[], filename: string, title?: string, ctx?: DocContext) {
  const [{ jsPDF }, autoTableMod, logo] = await Promise.all([import("jspdf"), import("jspdf-autotable"), loadLogo(ctx?.brand?.logoUrl)]);
  const autoTable = autoTableMod.default;
  const landscape = columns.length > 6;
  const doc = new jsPDF({ orientation: landscape ? "landscape" : "portrait", unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 40;
  const docTitle = title ?? filename;
  const printedAt = stamp();
  const brand = ctx?.brand ?? null;

  // ---- First-page letterhead ----
  doc.setFillColor(...BRAND.dark);
  doc.rect(0, 0, W, 6, "F");

  let x = M;
  const top = 30;
  if (logo) {
    const maxH = 46;
    const maxW = 110;
    const scale = Math.min(maxW / logo.w, maxH / logo.h);
    const lw = logo.w * scale;
    const lh = logo.h * scale;
    doc.addImage(logo.data, "PNG", M, top, lw, lh);
    x = M + lw + 14;
  }
  doc.setTextColor(...BRAND.text);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(brand?.name ?? SYSTEM_NAME, x, top + 14);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(...BRAND.muted);
  brandLines(brand).forEach((line, i) => doc.text(line, x, top + 28 + i * 11));

  // Title block on the right
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(...BRAND.primary);
  doc.text(docTitle, W - M, top + 14, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(...BRAND.muted);
  let ry = top + 28;
  if (ctx?.subtitle) {
    doc.text(ctx.subtitle, W - M, ry, { align: "right" });
    ry += 11;
  }
  doc.text(`${printedAt}  |  ${rows.length} record${rows.length === 1 ? "" : "s"}`, W - M, ry, { align: "right" });

  const ruleY = top + 62;
  doc.setDrawColor(...BRAND.primary);
  doc.setLineWidth(1.2);
  doc.line(M, ruleY, W - M, ruleY);

  // ---- Table ----
  autoTable(doc, {
    startY: ruleY + 14,
    head: [columns.map((c) => c.header)],
    body: rows.map((r) => columns.map((c) => cellText(r[c.key]))),
    theme: "grid",
    styles: { font: "helvetica", fontSize: 8, cellPadding: { top: 5, right: 6, bottom: 5, left: 6 }, textColor: BRAND.text, lineColor: BRAND.line, lineWidth: 0.4, overflow: "linebreak", valign: "middle" },
    headStyles: { fillColor: BRAND.primary, textColor: [255, 255, 255], fontStyle: "bold", lineColor: BRAND.primary },
    alternateRowStyles: { fillColor: BRAND.soft },
    margin: { left: M, right: M, top: 58, bottom: 44 },
    didDrawPage: (data) => {
      // Compact header on continuation pages
      if (data.pageNumber > 1) {
        doc.setFillColor(...BRAND.dark);
        doc.rect(0, 0, W, 4, "F");
        doc.setFont("helvetica", "bold");
        doc.setFontSize(9);
        doc.setTextColor(...BRAND.text);
        doc.text(brand?.name ?? SYSTEM_NAME, M, 30);
        doc.setFont("helvetica", "normal");
        doc.setTextColor(...BRAND.muted);
        doc.text(docTitle, W - M, 30, { align: "right" });
        doc.setDrawColor(...BRAND.line);
        doc.setLineWidth(0.6);
        doc.line(M, 38, W - M, 38);
      }
    },
  });

  // ---- Footer on every page (needs the final page count) ----
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setDrawColor(...BRAND.line);
    doc.setLineWidth(0.5);
    doc.line(M, H - 30, W - M, H - 30);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(150, 158, 155);
    const who = ctx?.printedBy ? `Printed by ${ctx.printedBy} on ${printedAt}` : `Generated on ${printedAt}`;
    doc.text(`${who}  |  Generated by ${SYSTEM_NAME}`, M, H - 18);
    doc.text(`Page ${p} of ${pages}`, W - M, H - 18, { align: "right" });
  }

  doc.save(`${safeName(filename)}.pdf`);
}
